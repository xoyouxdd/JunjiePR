"""Live, position-based rotation (rule version 2).

Forecasts are disposable projections. Occupancy, readiness, timeout evidence and
ordering clocks are authoritative. Legacy days retain their original reader.
All mutations run inside service.transaction, including confirmation and commit.
"""
from collections import Counter
from copy import deepcopy
import hashlib
import json
import math
from uuid import uuid4

from app.rotation.engine import ActionError, SHIFT_FINISH_MINUTES, SHIFT_PREPARE_MINUTES, push7_rank

EPS = 1e-8
SHIFT_PREVIEW_MINUTES = 20
MEAL_TO_REST_MINUTES = 20
BATCH_CHECK_IN_MINUTES = 15
BATCH_LEAD_MINUTES = 3
BATCH_MIN_PEOPLE = 16
OPENING_SHIFT_SECONDS = {7 * 3600, (7 * 60 + 15) * 60}
PRIORITY = {'sick': 0, 'push7': 1, 'off': 2, 'opening': 3, 'vacancy': 3, 'out': 4, 'push': 5}
POOLS = {'pending', 'rest', 'meal', 'away', 'other'}
WAITING_TO_REST = {'pending', 'walkback', 'op'}
UNSPECIFIED_ROUTE = object()


def enabled(eng):
    return eng.d.get('ruleVersion') == 2


def upgrade_opening_requests(state):
    """Previously saved V2 days only identified the line, not its new slot."""
    changed = False
    for line in state.get('lines', []):
        if 'adding' not in line:
            continue
        if line.pop('adding'):
            for post in line['posts']:
                if post.get('open') and not post.get('occ'):
                    post['openRequest'] = True
        changed = True
    return changed


def initialize(eng):
    changed = eng.d.get('taskWorkflow') != 2
    eng.d['taskWorkflow'] = 2
    eng.d['cooperativeEntry'] = False
    eng.d.setdefault('rotationTasks', {})  # Empty compatibility container for historical readers.
    changed = upgrade_opening_requests(eng.d) or changed
    for line in eng.d['lines']:
        if 'sortAt' not in line:
            line['sortAt'] = 0.0
            changed = True
        for post in line['posts']:
            if not post.get('key'):
                post['key'] = uuid4().hex
                changed = True
            if 'hold101Role' not in post:
                name = post['name'].replace(' ', '')
                role = {'塔台': 'tower', '塔协': 'tower_assist', '塔台协助': 'tower_assist'}.get(name)
                if role:
                    post['hold101Role'] = role
    for p in eng.P.values():
        if 'forecastOrder' not in p:
            # A persisted random tie breaker, never regenerated by refreshes.
            p['forecastOrder'] = uuid4().hex
            changed = True
    return changed


def shift_counts(eng):
    if not hasattr(eng, '_forecast_shift_counts'):
        eng._forecast_shift_counts = Counter(round(p['start'] * 60) for p in eng.P.values())
    return eng._forecast_shift_counts


def late_shift(eng, p):
    counts = shift_counts(eng)
    starts = sorted(counts, reverse=True)[:2]
    return any(round(p['start'] * 60) == start and counts[start] >= minimum
               for start, minimum in zip(starts, (3, 10)))


def finishes_on_exit(eng, p, now):
    return p['end'] <= now or (not late_shift(eng, p) and p['end'] - now <= SHIFT_FINISH_MINUTES)


def sort_stamp(clocks, lid, base):
    """Extend a collision interval in whole seconds, using the same rule in projections."""
    second = round(base * 60)
    collision = any(
        (other != lid and second == round(value * 60)) or
        (round(original * 60) <= second <= round(value * 60) and original < value)
        for other, (value, original) in clocks.items()
        if value > 0
    )
    return (max(second, max(round(value * 60) for value, _ in clocks.values()) + 1) / 60
            if collision else base)


def line_clocks(eng):
    return {line['id']: (line.get('sortAt', 0), line.get('sortBase', line.get('sortAt', 0)))
            for line in eng.d['lines'] if line['active']}


def set_sort_time(line, value, base=None):
    line['sortAt'] = value
    if base is None or value == base:
        line.pop('sortBase', None)
    else:
        line['sortBase'] = base


def batch_shift(eng, start_second):
    return start_second not in OPENING_SHIFT_SECONDS and shift_counts(eng)[start_second] >= BATCH_MIN_PEOPLE


def batch_member(eng, p):
    return (p['state'] == 'notyet' and p['role'] == 'rotation' and not p.get('manualPaused')
            and not p.get('initialPool') and batch_shift(eng, round(p['start'] * 60)))


def can_check_in(eng, p, now):
    return (eng.d['status'] == 'live' and str(round(p['start'] * 60)) not in eng.d.get('completedShiftBatches', {})
            and batch_member(eng, p)
            and p['start'] - BATCH_CHECK_IN_MINUTES <= now < p['start'] - BATCH_LEAD_MINUTES)


def checked_in(p):
    return p.get('batchCheckedInFor') == p['start']


def scheduled_opening(post):
    return bool(post.get('openAt') and not post.get('opened')
                and (not post.get('manual') or post.get('resumeScheduled')))


def indexes(line, at):
    from app.rotation.engine import _m
    result = []
    for i, post in enumerate(line['posts']):
        opened = post.get('open') or (scheduled_opening(post) and _m(post['openAt']) <= at + EPS)
        if (line.get('active') and opened and not post.get('hold') and not post.get('hold101')
                and not (post.get('closeAt') and not post.get('closeAfterRelief') and _m(post['closeAt']) <= at + EPS)):
            result.append(i)
    return result


def eligible(eng, p, at):
    return (p.get('state') in ('rest', 'meal', 'ready') and not p.get('exception')
            and not p.get('manualPaused') and p.get('role') in ('rotation', 'op')
            and (p.get('manualRestored') or p['start'] <= at < p['end'])
            and (p.get('manualRestored') or eng.can_board(p, at, at)))


def readiness(p):
    return float(p.get('readyAt') if p.get('readyAt') is not None else p['start'])


def deadline(eng, p, now, not_before=0):
    value = p.get('timeoutAt')
    if value is None and awaiting_shift_entry(p):
        return max(now, readiness(p), not_before) + 3
    value = float(value if value is not None else readiness(p) + 3)
    paused = eng.d.get('forecastPausedAt')
    if paused is not None:
        value += max(0, max(now, not_before) - max(paused, readiness(p)))
    return value


def occupant(eng, post, at):
    pid = post.get('occ')
    p = eng.P.get(pid)
    return None if p and p.get('state') == 'notyet' and p['start'] > at + EPS else pid


def seven_target(p, *, opening_crew=False):
    return (p['state'] == 'onpost' or opening_crew) and p['start'] == 420 and not p.get('sevenReplaced')


def demand(eng, line, at, reserved, requester=None, seven_owners=None, *, preview_shift=False, protected=()):
    """Return this line's highest eligible purpose, never a reserved person twice."""
    ix = indexes(line, at)
    if not ix:
        return None
    needs = []
    for i in ix:
        post = line['posts'][i]
        p = eng.P.get(occupant(eng, post, at))
        if not p or p['pid'] in reserved:
            continue
        opening_crew = preview_shift and p['state'] == 'notyet' and not (p.get('manualPaused') or p.get('initialPool'))
        if p['state'] != 'onpost' and not opening_crew:
            continue
        kind = None
        if p.get('requestedExit') == 'sick':
            kind = 'sick'
        elif seven_target(p, opening_crew=opening_crew):
            kind = 'push7'
        elif (p['end'] - at <= SHIFT_PREPARE_MINUTES and not late_shift(eng, p)):
            kind = 'off'
        elif p.get('requestedExit') == 'out':
            kind = 'out'
        else:
            for absence in p.get('absences', []):
                if not absence.get('done') and absence['start'] - eng.S['offLead'] <= at < absence['end']:
                    kind = 'out'
                    break
        if kind:
            if kind == 'push7' and seven_owners and seven_owners.get(p['pid']) not in (None, requester):
                continue
            due = p['end'] if kind == 'off' else at
            needs.append((PRIORITY[kind], due, -i, kind, p['pid']))
    if any(line['posts'][i].get('openRequest') and not occupant(eng, line['posts'][i], at) for i in ix):
        needs.append((PRIORITY['opening'], 0, 0, 'opening', None))
    if any(not occupant(eng, line['posts'][i], at) for i in ix):
        needs.append((PRIORITY['vacancy'], 0, 0, 'vacancy', None))
    if not needs and occupant(eng, line['posts'][ix[-1]], at) in protected:
        return None
    needs.append((PRIORITY['push'], 0, 0, 'push', None))
    rank, due, pos, kind, target = min(needs)
    return {'kind': kind, 'target': target, 'priority': rank, 'due': due, 'position': pos}


def route(eng, assignment, at, entry=None):
    line = eng.line(assignment['line'])
    ix = indexes(line, at)
    if entry is not None:
        ix = [i for i in ix if i >= entry]
    if not ix:
        raise ActionError('目标线路没有参与轮岗的开放岗位')
    kind = assignment['kind']
    target = assignment.get('target')
    if target:
        stop = next((i for i in ix if line['posts'][i].get('occ') == target), None)
        if stop is None:
            raise ActionError('接替目标已变化，请重新查看预排')
        ix = [i for i in ix if i <= stop]
        # A high-priority relief must remove its actual target, even when the
        # prefix contains a vacancy. Compact the prefix; never report a relief
        # as completed merely because an earlier empty slot was filled.
        retained = [(occupant(eng, line['posts'][i], at), line['posts'][i]['key']) for i in ix]
        retained = [(pid, key) for pid, key in retained if pid and pid != target]
        moves = [{'pid': assignment['owner'], 'from': None, 'to': line['posts'][ix[0]]['key']}]
        for (pid, source), destination in zip(retained, ix[1:]):
            key = line['posts'][destination]['key']
            if source != key:
                moves.append({'pid': pid, 'from': source, 'to': key})
        moves.append({'pid': target, 'from': line['posts'][stop]['key'], 'to': None,
                      'outcome': {'off': 'done', 'out': 'away', 'sick': 'sick'}.get(kind, 'rest')})
        return moves
    moves = []
    carry = assignment['owner']
    source = None
    for i in ix:
        post = line['posts'][i]
        moves.append({'pid': carry, 'from': source, 'to': post['key']})
        carry, source = occupant(eng, post, at), post['key']
        if not carry:
            break
    if carry:
        outcome = {'off': 'done', 'out': 'away', 'sick': 'sick'}.get(kind, 'rest')
        moves.append({'pid': carry, 'from': source, 'to': None, 'outcome': outcome})
    return moves


def settle_openings(line, moves, source_key=None):
    """Clear filled additions, carrying any displaced gap along the same line."""
    arrivals = {move['to'] for move in moves}
    departures = {move['from'] for move in moves} | {source_key}
    filled_keys = arrivals - departures
    filled = [post for post in line['posts'] if post.get('openRequest') and post['key'] in filled_keys]
    if not filled:
        return False
    vacated = departures - arrivals
    for post in filled:
        post['openRequest'] = False
    gaps = [post for post in line['posts'] if post['key'] in vacated and not post.get('openRequest')]
    for post in gaps[:len(filled)]:
        post['openRequest'] = True
    return True


def candidate_order(p):
    return round(readiness(p) * 60, 6), p['forecastOrder'], p['pid']


def candidates(eng, now):
    return sorted((p for p in eng.P.values() if eligible(eng, p, max(now, readiness(p)))), key=candidate_order)


def preparing_shift_start(p, now):
    return (p.get('state') == 'notyet' and p.get('role') == 'rotation' and not p.get('manualPaused')
            and p.get('initialPool') not in ('sick', 'away') and 0 < p['start'] - now <= SHIFT_PREVIEW_MINUTES)


def awaiting_shift_entry(p):
    return p['state'] == 'ready' and p.get('directShiftEntry') == p['start']


def shift_previews(eng, now):
    """Run the same planner on provisional candidates without changing live tasks."""
    from app.rotation.engine import Engine

    upcoming = [p for p in eng.P.values() if preparing_shift_start(p, now)]
    if not upcoming or eng.d.get('closed'):
        return {}
    seats = {pid: key for kind in ('crew', 'seven') for key, pid in eng.d['plan'][kind].items()}
    previews, expected_ready = {}, {}
    for p in upcoming:
        pid, start = p['pid'], p['start']
        if (start <= 435 or batch_shift(eng, round(start * 60))) and p.get('initialPool') != 'rest' and pid in seats:
            line, i, post = eng.plan_post(seats[pid])
            if i in indexes(line, start) and occupant(eng, post, start) in (None, pid):
                previews[pid] = {'line': line['id'], 'entryPost': post['name'], 'why': '开班预排'}
                continue
        delay = eng.S['breakMin'] if eng.opening_rest_candidate(p) else 0
        if p.get('initialPool') == 'rest':
            delay = 15
        expected_ready[pid] = start + delay
    if not expected_ready:
        return previews
    projected = Engine({**eng.d, 'persons': deepcopy(eng.P), 'lines': deepcopy(eng.d['lines'])}, eng.S, eng.h)
    for pid in previews:
        _, _, post = projected.plan_post(seats[pid])
        post['occ'] = pid  # The normal occupancy reader ignores the seat until shift start.
    for pid, ready_at in expected_ready.items():
        projected.P[pid].update(state='rest', readyAt=ready_at)
    plan(projected, now, preview_shift=True)
    for pid in expected_ready:
        person = projected.P[pid]
        task = task_view(projected, person, now)
        if person.get('assign'):
            previews[pid] = {**person['assign'], 'entryPost': task['entryPost'] if task else None,
                             'routes': task['routes'] if task else []}
    return previews


def push7_history(eng):
    if 'push7History' not in eng.d:
        read_history = getattr(eng.h, 'push7_history', None)
        eng.d['push7History'] = read_history() if read_history else {}
    history = dict(eng.d['push7History'])
    for target in eng.P.values():
        completion = target.get('push7Completion')
        if completion:
            pid = completion['owner']
            count, day, minute = push7_rank(history, pid)
            history[pid] = (count + 1, *max((day, minute), (eng.d['date'], completion['at'])))
    return history


def plan(eng, now, *, only_pid=None, preview_shift=False, batch_person=None, protected=()):
    """One global pass; a selected line's projected clock advances immediately."""
    initialize(eng)
    before = {pid: deepcopy(p.get('assign')) for pid, p in eng.P.items()}
    seven_owners = {a['target']: pid for pid, a in before.items()
                    if only_pid is not None and a and a.get('kind') == 'push7'
                    and max(readiness(eng.P[pid]), a.get('notBefore', 0)) <= now + EPS}
    for p in eng.P.values():
        p['assign'] = None
    clocks = line_clocks(eng)
    reserved = set()
    seats = {line['id']: deepcopy(line) for line in eng.d['lines']}
    people = [batch_person] if batch_person is not None else candidates(eng, now)
    if only_pid is not None:
        # Confirm from actual positions. Keep the fair owner's claim to an
        # immediately available morning relief while recomputing its route.
        people = [p for p in people if p['pid'] == only_pid]
    waiting = people.copy()
    history = None
    while waiting:
        p = waiting[0]
        at = now if batch_person is not None else max(now, readiness(p))
        options = []
        for order, real in enumerate(eng.d['lines']):
            line = seats[real['id']]
            option_at = at
            if batch_person is None and not indexes(line, at) and line.get('active'):
                from app.rotation.engine import _m
                future = [_m(x['openAt']) for x in line['posts']
                          if scheduled_opening(x) and _m(x['openAt']) > at]
                if future:
                    option_at = min(future)
            if not p.get('manualRestored') and not eng.can_board(p, max(option_at, readiness(p)), now):
                continue
            purpose = demand(eng, line, option_at, reserved, p['pid'], seven_owners, preview_shift=preview_shift, protected=protected)
            if not purpose:
                continue
            ix = indexes(line, option_at)
            if not purpose['target'] and seven_owners:
                occupied = [occupant(eng, line['posts'][i], option_at) for i in ix]
                if all(occupied) and seven_owners.get(occupied[-1], p['pid']) != p['pid']:
                    continue
            if (purpose['kind'] == 'push' and not late_shift(eng, p)
                    and option_at >= max(q['end'] for q in eng.P.values()) - eng.S.get('closeStopPush', 20)):
                continue
            key = (option_at > at + EPS, purpose['priority'], purpose.get('due', 0), purpose.get('position', 0),
                   clocks[line['id']][0], -len(ix), order)
            options.append((key, real, purpose, option_at))
        if not options:
            waiting.pop(0)
            continue
        _, line, purpose, option_at = min(options, key=lambda x: x[0])
        kind = purpose['kind']
        if kind == 'push7' and only_pid is None and batch_person is None:
            if history is None:
                history = push7_history(eng)
            # Existing readiness and stable tie order break a complete tie.
            p = min((q for q in waiting if max(now, readiness(q)) <= at + EPS
                     and (q.get('manualRestored') or eng.can_board(q, option_at, now))),
                    key=lambda q: push7_rank(history, q['pid']))
        waiting.remove(p)
        at = option_at
        why = {'sick': '推病假', 'push7': '推7点', 'off': '推下班', 'opening': '顺推加岗',
               'vacancy': '补空岗', 'out': '推出圈', 'push': '普通顺推'}[kind]
        p['assign'] = {'owner': p['pid'], 'line': line['id'], 'kind': kind, 'target': purpose.get('target'),
                       'mode': 'chain' if purpose.get('target') else 'push',
                       'why': why, 'departAt': max(readiness(p), at if at > max(now, readiness(p)) else readiness(p)),
                       'allowedAt': max(readiness(p), at if at > max(now, readiness(p)) else readiness(p)),
                       'notBefore': at if at > max(now, readiness(p)) else 0, 'forecast': True}
        if purpose.get('target'):
            reserved.add(purpose['target'])
        projected = seats[line['id']]
        projected_ix = indexes(projected, at)
        target_i = next((i for i in projected_ix if projected['posts'][i].get('occ') == purpose.get('target')), None)
        advances_clock = kind != 'opening' and (not purpose.get('target') or target_i == projected_ix[-1])
        # Only the virtual occupancy advances. Actual positions are never touched.
        shadow = deepcopy(p['assign'])
        original = eng.d['lines']
        try:
            eng.d['lines'] = list(seats.values())
            moves = route(eng, shadow, at)
        finally:
            eng.d['lines'] = original
        bykey = {x['key']: x for x in projected['posts']}
        for move in moves:
            if move['from']:
                bykey[move['from']]['occ'] = None
        for move in moves:
            if move['to']:
                bykey[move['to']]['occ'] = move['pid']
        settle_openings(projected, moves)
        if advances_clock:
            stamp = sort_stamp(clocks, line['id'], at)
            clocks[line['id']] = (stamp, at)
    # Shared display group only; members always execute independently.
    groups = {}
    for p in people:
        if p.get('assign'):
            a = p['assign']
            groups.setdefault((a['line'], math.floor(a['departAt'])), []).append(p['pid'])
    for members in groups.values():
        for pid in members:
            eng.P[pid]['assign']['batchSize'] = len(members)
            eng.P[pid]['assign']['members'] = members
    return any(before[pid] != p.get('assign') for pid, p in eng.P.items())


def post_comparison(eng, line):
    return [{'key': x['key'], 'name': x['name'], 'occ': x.get('occ'),
             'occName': eng.P.get(x.get('occ'), {}).get('name'), 'open': x.get('open'),
             'hold': bool(x.get('hold') or x.get('hold101'))} for x in line['posts']]


def task_view(eng, p, now):
    a = p.get('assign')
    if not a:
        return None
    from app.rotation import workflow as W
    at = max(now, readiness(p), a.get('notBefore', 0))
    try:
        moves = route(eng, a, at)
    except ActionError:
        return None
    line = eng.line(a['line'])
    before = post_comparison(eng, line)
    after = deepcopy(before)
    for move in moves:
        for post in after:
            if post['key'] == move['from']:
                post.update(occ=None, occName=None)
    for move in moves:
        for post in after:
            if post['key'] == move['to']:
                post.update(occ=move['pid'], occName=eng.P[move['pid']]['name'])
    fake = {'moves': moves, 'status': 'forecast', 'template': a}
    return {'id': p['pid'], 'revision': p.get('confirmationSequence', 0), 'batch': str(math.floor(readiness(p))),
            'batchSize': a.get('batchSize', 1), 'line': a['line'], 'entryPost': next(x['name'] for x in before if x['key'] == moves[0]['to']),
            'sortAt': float(line.get('sortAt', 0)), 'participatingPosts': len(indexes(line, at)), 'reason': a['why'],
            'allowedAt': a.get('allowedAt', readiness(p)), 'deadlineAt': deadline(eng, p, now, a.get('notBefore', 0)), 'status': 'forecast',
            'kind': a['kind'], 'mode': a['mode'], 'routes': W.route_view(eng, fake), 'beforePosts': before, 'afterPosts': after,
            'push7Route': hashlib.sha256(json.dumps(moves, sort_keys=True).encode()).hexdigest()
            if a['kind'] == 'push7' else None,
            'transferredFromName': None}


def remove(eng, p, now):
    from app.rotation import workflow as W
    line, i = eng.find_post(p['pid'])
    if line is not None:
        eng._leave_line(p, line, i, max(now, p.get('lineStart') or now))
        line['posts'][i]['occ'] = None
    W.finish_continuous(p, max(now, p.get('continuousStart') or now))
    p.update(assign=None, line=None, arriveAnchor=None, readySince=None)
    p.pop('batchOnPost', None)
    p.pop('directShiftEntry', None)


def restore(p, now):
    p['manualRestored'] = bool(p.get('manualRestored') or now < p['start'] or now >= p['end']
                               or p.get('state') in ('sick', 'done', 'excluded'))
    p['manualPaused'] = False
    p['role'] = 'rotation'
    p.pop('requestedExit', None)


def cancel_active_absences(eng, p, now, actor):
    for absence in p.get('absences', []):
        if not absence.get('done') and absence['start'] <= now < absence['end']:
            absence.update(done=True, cancelledByManual=True)
            eng.h.log('cancel_fixed_absence', actor, p['pid'], None, None,
                      {k: absence.get(k) for k in ('start', 'end', 'label')})


def pool(eng, pid, destination, now, actor, remaining=None, repeat_meal=False, automatic=False):
    if destination not in POOLS:
        raise ActionError('人员池不正确')
    p = eng.person(pid)
    if eng.held(pid):
        raise ActionError('请先解除定岗')
    if destination == 'meal' and p['state'] != 'meal' and not eng.meal_eligible(p):
        raise ActionError('此人班次未达到用餐工时要求')
    converting_rest = destination == 'meal' and p['state'] in ('rest', 'ready')
    break_start = now
    credited_rest = None
    if converting_rest:
        if p.get('ate'):
            raise ActionError('此人今天已吃饭，无法将本次休息改为吃饭')
        if p.get('readyAt') is None or now + EPS >= p['readyAt']:
            raise ActionError('本次休息已结束，请按当前轮岗安排处理')
        break_start = p.get('breakStart')
        if break_start is None:
            break_start = p.get('arriveAnchor')
        break_start = now if break_start is None else break_start
        credited_rest = min(eng.S['mealMin'], max(0, now - break_start))
        remaining = eng.S['mealMin'] - credited_rest
        options = eng.meal_options(p, now, meal_minutes=remaining)
        if not (options['canChoose'] or options['forced']):
            raise ActionError('当前不满足吃饭条件或轮岗储备不足，继续原休息')
    if destination == 'meal' and p.get('ate') and not repeat_meal:
        raise ActionError('此人已进过吃饭区，是否继续？')
    old_exception = p.pop('exception', None)
    if not automatic:
        cancel_active_absences(eng, p, now, actor)
    remove(eng, p, now)
    restore(p, now)
    p['confirmationSequence'] = p.get('confirmationSequence', 0) + 1
    p.update(state=destination, away=None, readyAt=None, breakStart=None, breakKind=None, timeoutAt=None)
    if destination in ('rest', 'meal'):
        duration = float(remaining) if remaining is not None else eng.S['mealMin' if destination == 'meal' else 'breakMin']
        if not math.isfinite(duration) or not 0 <= duration <= 24 * 60:
            raise ActionError('剩余时间须在0至1440分钟内')
        p.update(readyAt=now + duration, timeoutAt=now + duration + 3, breakStart=break_start,
                 breakKind=destination, arriveAnchor=break_start)
        if destination == 'meal':
            p['ate'] = True
    elif destination == 'away':
        p['away'] = {'reason': '出圈', 'until': None}
    elif destination == 'other':
        p['manualPaused'] = True
    detail = {'pool': destination, 'remaining': remaining, 'endedException': old_exception}
    if credited_rest is not None:
        detail['credited_rest'] = credited_rest
    eng.h.log('pool_move', actor, pid, None, None, detail)
    plan(eng, now)


def execute_moves(eng, p, assignment, moves, now, actor, manual=False, source_key=None, *, base=None):
    from app.rotation import workflow as W
    line = eng.line(assignment['line'])
    ix = indexes(line, now)
    target_index = next((i for i in ix if line['posts'][i].get('occ') == assignment.get('target')), None)
    update_sort = assignment['kind'] != 'opening' and (not assignment.get('target') or target_index == ix[-1])
    base = now if base is None else base
    # A preceding move may have a future start. Preserve nonnegative segments.
    earliest_stamp = max(base, *(eng.P[m['pid']].get('lineStart') or 0 for m in moves))
    if update_sort and not manual:
        stamp = sort_stamp(line_clocks(eng), line['id'], earliest_stamp)
    else:
        stamp = earliest_stamp
    locations = {post['key']: (L, i, post) for L in eng.d['lines'] for i, post in enumerate(L['posts'])}
    for move in moves:
        q = eng.P[move['pid']]
        if move['from']:
            oldline, i, post = locations[move['from']]
            eng._leave_line(q, oldline, i, stamp)
            post['occ'] = None
        if not move['to']:
            W.finish_continuous(q, stamp)
            outcome = move.get('outcome', 'rest')
            if outcome == 'rest' and not q.get('manualRestored') and finishes_on_exit(eng, q, now):
                outcome = 'done'
            away = {'reason': '出圈', 'until': None} if outcome == 'away' else None
            if outcome == 'away' and q.get('requestedExit') != 'out':
                absence = eng.next_absence(q, now)
                if absence and absence['start'] - eng.S['offLead'] <= now < absence['end']:
                    away = {'reason': absence.get('label') or '出圈', 'until': absence['end'], 'fixed': True}
            q.update(state='pending' if outcome == 'rest' else outcome, assign=None,
                     readyAt=None, breakStart=None, breakKind=None, arriveAnchor=None,
                     walkbackSince=now, away=away)
            q.pop('requestedExit', None)
            q.pop('batchOnPost', None)
    for move in moves:
        if move['to']:
            q = eng.P[move['pid']]
            _, _, post = locations[move['to']]
            post.update(occ=q['pid'], since=stamp)
            eng._enter(q, line, stamp)
            q.pop('directShiftEntry', None)
            q['departedAt'] = stamp
    completion = None
    if assignment['kind'] == 'push7':
        target = eng.P[assignment['target']]
        completion = uuid4().hex
        target['push7Completion'] = {'id': completion, 'owner': p['pid'], 'at': now}
        W.clear_completed_seven_badges(eng, {'template': {'mode': 'push7', 'target': target['pid']}}, p['pid'])
    elif manual:
        for move in moves:
            if not move['to'] and '7点岗' in eng.P[move['pid']].get('flags', []):
                W.clear_completed_seven_badges(eng, {'template': {'mode': 'push7', 'target': move['pid']}}, p['pid'])
        p['flags'] = [flag for flag in p.get('flags', []) if flag != '推7点']
    if update_sort and not manual:
        set_sort_time(line, stamp, base)
    filled_opening = settle_openings(line, moves, source_key)
    evidence = p.pop('exception', None)
    detail = {'purpose': assignment['kind'], 'moves': moves, 'timeout': evidence, 'effectiveAt': stamp}
    if completion:
        detail.update(push7_execution=completion, target=assignment['target'])
    if manual:
        detail['update_sort_time'] = bool(assignment.get('update_sort_time') and not filled_opening)
    eng.h.log('manual_forecast_complete' if manual else 'depart', actor, p['pid'], line['id'], None, detail)
    p['confirmationSequence'] = p.get('confirmationSequence', 0) + 1
    p.pop('timeoutAt', None)
    return filled_opening


def confirmation_plan(eng, pid, now):
    """One real candidate, without changing the shared provisional queue."""
    saved = {key: p.get('assign') for key, p in eng.P.items()}
    try:
        plan(eng, now, only_pid=pid)
        p = eng.person(pid)
        return deepcopy(p.get('assign')), task_view(eng, p, now)
    finally:
        for key, assignment in saved.items():
            eng.P[key]['assign'] = assignment


def execute(eng, pid, now, actor, expected_line, expected_push7=UNSPECIFIED_ROUTE, *, expected_kind=None):
    p = eng.person(pid)
    if p.get('exception') or p['state'] == 'exception':
        raise ActionError('已超时，请由大屏、主管、TR或经理拖拽安排')
    if not eligible(eng, p, now) or now + EPS < readiness(p):
        raise ActionError('餐休尚未结束或当前不可上岗')
    plan(eng, now)
    predicted_line = (p.get('assign') or {}).get('line')
    a, task = confirmation_plan(eng, pid, now)
    if not a:
        raise ActionError('当前没有可确认的轮岗路线，请刷新查看安排')
    if a['kind'] == 'push7' and getattr(actor, 'kind', None) not in (None, 'member'):
        raise ActionError('推7点须由接替人通过本人待办确认')
    if now + EPS < a.get('notBefore', 0):
        raise ActionError('尚未到计划加岗时间')
    route_changed = expected_push7 is not UNSPECIFIED_ROUTE and expected_push7 != task['push7Route']
    opening_changed = expected_kind not in (None, a['kind']) and 'opening' in (expected_kind, a['kind'])
    if expected_line != a['line'] or route_changed or opening_changed:
        waiting = []
        if predicted_line == expected_line and expected_line != a['line']:
            for previous in candidates(eng, now):
                if previous['pid'] == pid:
                    break
                if (previous.get('assign') or {}).get('line') == a['line']:
                    waiting.append({'pid': previous['pid'], 'name': previous['name'], 'line': a['line']})
        return {'ok': True, 'line_changed': True, 'previous_line': expected_line,
                'line': a['line'], 'task': task, 'waiting_predecessors': waiting}
    moves = route(eng, a, now)
    execute_moves(eng, p, a, moves, now, actor)
    finish_deferred_closures(eng, now)
    plan(eng, now)
    return {'ok': True, 'line_changed': False, 'executed': True}


def expire_closed_line_opening(line, post, now):
    """A scheduled addition only gets one chance, at its due time."""
    from app.rotation.engine import _m

    if line.get('active') or not post.get('openAt') or post.get('open') or post.get('openExpired'):
        return
    # Older states could already mark the missed schedule checked while leaving its request set.
    pending = (scheduled_opening(post) or post.get('resumeScheduled')
               or (post.get('opened') and not post.get('manual') and post.get('openRequest')))
    if pending and now >= _m(post['openAt']):
        post.update(open=False, opened=True, openRequest=False, openExpired=True, draftClosed=True, manual=True)
        post.pop('resumeScheduled', None)
        post.pop('resumeOpen', None)


def schedule_closure(eng, line, i, now):
    post = line['posts'][i]
    worker = eng.P.get(post.get('occ'))
    # A due departure on the closing seat can leave directly. Otherwise keep
    # a seat in a pending relief route open until that relief has executed.
    target = next((eng.P[line['posts'][j]['occ']] for j in reversed(indexes(line, now))
                   if j > i and line['posts'][j].get('occ') in eng.P
                   and eng.preparing_shift_end(eng.P[line['posts'][j]['occ']], now)), None)
    if target and not (worker and worker['end'] <= now):
        post['closeAfterRelief'] = target['pid']
    else:
        close_post(eng, line, i, now, 'system')


def finish_deferred_closures(eng, now):
    for line in eng.d['lines']:
        for i, post in enumerate(line['posts']):
            pid = post.get('closeAfterRelief')
            if pid and not post.get('hold') and not post.get('hold101'):
                target_line, target_index = eng.find_post(pid)
                worker = eng.P.get(post.get('occ'))
                if (target_line is not line or target_index <= i
                        or not eng.preparing_shift_end(eng.P[pid], now)
                        or worker and worker['end'] <= now):
                    close_post(eng, line, i, now, 'system')


def release_reserved_seat(eng, p, *plans):
    for plan in plans:
        if p['pid'] in plan:
            _, _, post = eng.plan_post(plan[p['pid']])
            if post.get('occ') == p['pid']:
                post.update(occ=None, since=None)


def due_batch(eng, now):
    start_second = round((now + BATCH_LEAD_MINUTES) * 60)
    start = start_second / 60
    if (abs(start - now - BATCH_LEAD_MINUTES) > EPS or not batch_shift(eng, start_second)
            or str(start_second) in eng.d.get('completedShiftBatches', {})):
        return []
    return [p for p in eng.P.values() if abs(p['start'] - start) <= EPS and batch_member(eng, p)]


def run_due_batch(eng, now, execute_batch):
    booked = due_batch(eng, now)
    if booked:
        start = booked[0]['start']
        eng.d.setdefault('completedShiftBatches', {})[str(round(start * 60))] = now
        execute_batch(eng, now, start, booked)


def batch_handoff(eng, before_posts, after_posts, post_key):
    index = next(i for i, post in enumerate(before_posts) if post['key'] == post_key)
    original = before_posts[index]
    if not original['occ']:
        return None
    handoff = {'post': original['name'], 'name': original['occName']}
    for destination, post in enumerate(after_posts):
        if post['occ'] == original['occ']:
            return {**handoff, 'outcome': 'post', 'destination': post['name'],
                    'steps': destination - index}
    return {**handoff, 'outcome': eng.P[original['occ']]['state']}


def run_batch(eng, now, start, booked):
    resting = [p for p in eng.P.values() if p['state'] in ('rest', 'ready', 'meal')
               and not awaiting_shift_entry(p)
               and now <= readiness(p) <= start and eligible(eng, p, readiness(p))
               and not any(not a.get('done') and now < a['end'] and a['start'] <= readiness(p)
                           for a in p.get('absences', []))]
    arriving = [p for p in booked if checked_in(p) and start < p['end'] and eng.can_board(p, start, now)
                and not any(a['start'] <= start < a['end'] for a in p.get('absences', []))]
    people = sorted(resting, key=candidate_order) + sorted(arriving, key=lambda p: (p['forecastOrder'], p['pid']))
    seat_plans = [{pid: key for key, pid in eng.d['plan'][kind].items()} for kind in ('crew', 'seven')]
    for p in booked:
        release_reserved_seat(eng, p, *seat_plans)
    if not people:
        return
    before = {line['id']: post_comparison(eng, line) for line in eng.d['lines']}
    placed = {}
    for p in people:
        base = p['start'] if p['state'] == 'notyet' else readiness(p)
        plan(eng, now, batch_person=p, protected=placed)
        assignment = p.get('assign')
        p.pop('batchResult', None)
        if not assignment:
            pool(eng, p['pid'], 'rest', now, 'system', remaining=15, automatic=True)
            # Signed-in employees may rest before their scheduled start without
            # granting the manual override used for forced placements.
            p['manualRestored'] = False
            p['batchResult'] = {'start': start, 'restUntil': p['readyAt']}
            continue
        moves = route(eng, assignment, now)
        execute_moves(eng, p, assignment, moves, now, 'system', base=base)
        line_id = assignment['line']
        placed[p['pid']] = line_id
        p['batchOnPost'] = start
        finish_deferred_closures(eng, now)

    after = {lid: post_comparison(eng, eng.line(lid)) for lid in set(placed.values())}
    for pid, lid in placed.items():
        p = eng.P[pid]
        line, i = eng.find_post(pid)
        # A separately due closure can remove a seat used earlier in the batch.
        if line is None:
            if p['state'] == 'pending':
                pool(eng, pid, 'rest', now, 'system', remaining=15, automatic=True)
                p['manualRestored'] = False
                p['batchResult'] = {'start': start, 'restUntil': p['readyAt']}
            continue
        p['batchResult'] = {'start': start, 'line': lid, 'post': line['posts'][i]['name'],
                            'handoff': batch_handoff(eng, before[lid], after[lid], line['posts'][i]['key']),
                            'beforePosts': before[lid], 'afterPosts': after[lid]}


def tick(eng, now, *, advance_batches=False, execute_batch=run_batch):
    from app.rotation.engine import _m
    initialized = initialize(eng)
    if eng.d['status'] != 'live':
        return False
    if eng.should_end(now):
        eng.end_day(now)
        return True
    before = json.dumps(eng.d, sort_keys=True, ensure_ascii=False)
    if not eng.d.get('dailyOpening') and eng.P:
        first = min(p['start'] for p in eng.P.values())
        freeze_at = first - BATCH_LEAD_MINUTES if batch_shift(eng, round(first * 60)) else first
        eng._freeze_daily_opening(now, freeze_at=freeze_at)
    seats = {pid: key for key, pid in eng.d['plan']['crew'].items()}
    seven = {pid: key for key, pid in eng.d['plan']['seven'].items()}
    arriving_relief = []
    for line in eng.d['lines']:
        for i, post in enumerate(line['posts']):
            expire_closed_line_opening(line, post, now)
            if line['active'] and scheduled_opening(post) and now >= _m(post['openAt']):
                post.update(open=True, opened=True, openRequest=True, manual=False, closedAuto=False)
                post.pop('draftClosed', None)
                post.pop('resumeScheduled', None)
            if post.get('closeAt') and post.get('open') and not post.get('closedAuto') and not post.get('closeAfterRelief') and now >= _m(post['closeAt']):
                if not post.get('hold') and not post.get('hold101'):
                    schedule_closure(eng, line, i, now)
    for p in list(eng.P.values()):
        if p['state'] == 'notyet' and now >= p['start'] and not p.get('manualPaused'):
            initial = p.pop('initialPool', None)
            if initial:
                if initial == 'sick':
                    p.update(state='sick', manualPaused=True)
                else:
                    pool(eng, p['pid'], initial, now, 'system', remaining=15 if initial == 'rest' else None)
                continue
            start_second = round(p['start'] * 60)
            if batch_member(eng, p) or (start_second not in OPENING_SHIFT_SECONDS and p['role'] == 'rotation'
                                        and str(start_second) in eng.d.get('completedShiftBatches', {})):
                release_reserved_seat(eng, p, seats, seven)
                p.update(state='rest', readyAt=p['start'], breakKind='rest')
                continue
            if p['start'] > 435 and p['role'] == 'rotation' and not eng.d.get('closed'):
                release_reserved_seat(eng, p, seats, seven)
                p.update(state='ready', readyAt=p['start'], readySince=p['start'],
                         breakKind='rest', directShiftEntry=p['start'])
                p.pop('timeoutAt', None)
            else:
                eng._shift_start(p, now, seats, seven)
            if p['state'] == 'ready' and not awaiting_shift_entry(p):
                if p['pid'] not in eng.d['plan']['push7']:
                    p.update(state='pending', readyAt=None)
                elif p['start'] == 435:
                    arriving_relief.append(p['pid'])
            if p['state'] == 'onpost':
                L, i = eng.find_post(p['pid'])
                opening = L['posts'][i].pop('openRequest', False)
                ix = indexes(L, now)
                if not opening and ix and i == ix[0]:
                    set_sort_time(L, float(p['start']))
        if p['state'] == 'op' and now >= _m(eng.S['opReleaseAt']):
            p.update(state='pending', readyAt=None)
        if p['state'] == 'meal' and p.get('readyAt') is not None and now + EPS >= p['readyAt'] - MEAL_TO_REST_MINUTES:
            p.update(state='rest', breakKind='meal_rest')
        if p['state'] == 'away' and (p.get('away') or {}).get('until') is not None and now >= p['away']['until']:
            for a in p.get('absences', []):
                if a['end'] == p['away']['until']:
                    a['done'] = True
            pool(eng, p['pid'], 'rest', now, 'system', remaining=15, automatic=True)
        if p['state'] in ('rest', 'meal', 'ready', 'pending'):
            for a in p.get('absences', []):
                if not a.get('done') and a['start'] <= now < a['end']:
                    pool(eng, p['pid'], 'away', now, 'system', automatic=True)
                    p['away'].update(until=a['end'], fixed=True)
                    break
        if not p.get('manualRestored') and (
            (p['state'] in WAITING_TO_REST and finishes_on_exit(eng, p, now))
            or (now >= p['end'] and (p['state'] in ('rest', 'meal', 'ready', 'away', 'exception')
                                     or p['state'] == 'onpost' and late_shift(eng, p) and not eng.held(p['pid'])))
        ):
            remove(eng, p, now)
            p['state'] = 'done'
    finish_deferred_closures(eng, now)
    if advance_batches:
        run_due_batch(eng, now, execute_batch)
    plan(eng, now)
    unused_relief = [eng.P[pid] for pid in arriving_relief if eng.P[pid]['state'] == 'ready'
                     and (eng.P[pid].get('assign') or {}).get('kind') not in ('push7', 'sick')]
    for p in unused_relief:
        p['flags'] = [flag for flag in p.get('flags', []) if flag != '推7点']
        eng.start_opening_rest(p, now)
    if unused_relief:
        plan(eng, now)
    available = any(indexes(L, now) for L in eng.d['lines'])
    paused_at = eng.d.get('forecastPausedAt')
    if not available and paused_at is None:
        eng.d['forecastPausedAt'] = now
    elif available and paused_at is not None:
        for p in eng.P.values():
            if p['state'] in ('rest', 'meal', 'ready') and not (
                    awaiting_shift_entry(p) and p.get('timeoutAt') is None):
                p['timeoutAt'] = deadline(eng, p, now)
        eng.d.pop('forecastPausedAt', None)
    if available:
        for p in eng.P.values():
            assignment = p.get('assign')
            if awaiting_shift_entry(p) and p.get('timeoutAt') is None:
                if assignment and now + EPS >= assignment.get('notBefore', 0):
                    p['timeoutAt'] = now + 3
            expires = deadline(eng, p, now)
            if assignment and now + EPS >= assignment.get('notBefore', 0) and now + EPS >= expires:
                p['exception'] = {'at': now, 'deadlineAt': expires,
                                  'assignment': deepcopy(p['assign']), 'allowedAt': readiness(p)}
                p.update(state='exception', assign=None)
                eng.h.log('forecast_timeout', 'system', p['pid'], p['exception']['assignment']['line'], None, p['exception'])
        plan(eng, now)
    return initialized or before != json.dumps(eng.d, sort_keys=True, ensure_ascii=False)


def close_post(eng, line, i, now, actor):
    post = line['posts'][i]
    if post.get('hold') or post.get('hold101'):
        raise ActionError('请先解除定岗')
    if post.get('occ'):
        p = eng.P[post['occ']]
        if p.get('state') == 'onpost':
            remove(eng, p, now)
            p.update(state='done' if finishes_on_exit(eng, p, now) else 'pending',
                     readyAt=None, breakStart=None, breakKind=None)
    post.update(open=False, occ=None, manual=True, closedAuto=True, draftClosed=True, openRequest=False)
    post.pop('closeAfterRelief', None)
    set_sort_time(line, now)
    eng.h.log('post_close', actor, None, line['id'], post['name'], {})


def head_occupants(eng, now):
    result = {}
    for line in eng.d['lines']:
        ix = indexes(line, now)
        result[line['id']] = occupant(eng, line['posts'][ix[0]], now) if ix else None
    return result


def update_manual_sort_times(eng, before, now, actor, requested):
    """Manual placement changes sort clocks only after an explicit opt-in."""
    if not requested:
        return
    after = head_occupants(eng, now)
    for line in eng.d['lines']:
        pid = after[line['id']]
        if pid and pid != before.get(line['id']) and eng.P[pid]['state'] == 'onpost':
            old = line.get('sortAt', 0)
            set_sort_time(line, now)
            ix = indexes(line, now)
            eng.h.log('sort_time', actor, pid, line['id'], line['posts'][ix[0]]['name'],
                      {'before': old, 'after': now, 'source': 'manual_drag'})


def manual_place(eng, pid, lid, i, mode, now, actor, *, update_sort_time=False):
    if not isinstance(update_sort_time, bool):
        raise ActionError('是否更新表头轮岗时间必须为布尔值')
    p = eng.person(pid)
    line, i, post = eng.post(lid, i)
    participating = indexes(line, now)
    if not line.get('active') or i not in participating:
        raise ActionError('目标岗位未开放或已定岗')
    if eng.held(pid):
        raise ActionError('请先解除定岗')
    source_line, source_i = eng.find_post(pid)
    if source_line is line and source_i == i:
        raise ActionError('人员已在该岗位')
    if mode not in ('push', 'swap'):
        raise ActionError('请选择顺推或直接交换')
    original = post.get('occ')
    assignment = {'owner': pid, 'line': lid, 'kind': 'push', 'update_sort_time': update_sort_time}
    from_head = mode == 'push' and source_line is None and i == participating[0]
    original_task = (p.get('exception') or {}).get('assignment') or {}
    if from_head and original_task.get('kind') == 'push7' and original_task.get('line') == lid:
        target = eng.P.get(original_task.get('target'))
        if target and seven_target(target) and target.get('requestedExit') != 'sick' and any(
                line['posts'][j].get('occ') == target['pid'] for j in participating):
            assignment.update(kind='push7', target=target['pid'])
    before_heads = head_occupants(eng, now)
    source_key = source_line['posts'][source_i]['key'] if source_line is not None else None
    continuous_start = p.get('continuousStart') if p.get('state') == 'onpost' else None
    cancel_active_absences(eng, p, now, actor)
    remove(eng, p, now)
    if continuous_start is not None:
        p['continuousStart'] = continuous_start
    restore(p, now)
    if mode == 'swap':
        moves = [{'pid': pid, 'from': None, 'to': post['key']}]
        if original:
            moves.append({'pid': original, 'from': post['key'], 'to': source_key, 'outcome': 'rest'})
    else:
        moves = route(eng, assignment, now, entry=i)
        if from_head and not moves[-1]['to']:
            relieved = eng.P[moves[-1]['pid']]
            if seven_target(relieved) and relieved.get('requestedExit') != 'sick':
                assignment.update(kind='push7', target=relieved['pid'])
        if assignment['kind'] == 'push7':
            update_sort_time = update_sort_time and moves[-1]['from'] == line['posts'][participating[-1]]['key']
            assignment['update_sort_time'] = update_sort_time
    # Cross-line swaps need each destination's actual line, not the entry line.
    if source_key and mode == 'swap' and original:
        q = eng.P[original]
        eng._leave_line(q, line, i, now)
        source_line['posts'][source_i].update(occ=original, since=now)
        eng._enter(q, source_line, now)
        eng.h.log('manual_swap', actor, q['pid'], source_line['id'], source_line['posts'][source_i]['name'],
                  {'fromLine': lid, 'fromPost': post['name'], 'with': pid})
        post['occ'] = None
        moves = [moves[0]]
    filled_opening = execute_moves(eng, p, assignment, moves, now, actor, manual=True,
                                   source_key=source_key if source_line is line else None)
    update_manual_sort_times(eng, before_heads, now, actor, update_sort_time and not filled_opening)
    plan(eng, now)


def token(eng, p, action):
    value = [eng.d.get('confirmationEpoch'), eng.d['date'], p['pid'], action,
             p.get('confirmationSequence', 0), p['state'], p.get('readyAt')]
    if action == 'batch_check_in':
        value.append(p['start'])
    return hashlib.sha256(json.dumps(value, ensure_ascii=False).encode()).hexdigest()
